def test_wape_handles_zero_sales():
    assert metrics.wape_safe([0, 0, 0], [1, 0, 2]) == (1.0, "all actual sales were zero: mean absolute error in tickets instead")
    v, note = metrics.wape_safe([0, 10, 0], [2, 8, 0])
    assert note is None and v == pytest.approx(0.4)


def test_checkout_abandonment_model_end_to_end_with_first_time_and_returning(tmp_path):
    exp = write_export(tmp_path, {"checkout_abandonment": checkout_fixture()})
    r = subprocess.run([PY, "scripts/validate_datasets.py", "--data", str(exp), "--allow-test-fixture"], cwd=BASE, capture_output=True, text=True)
    assert r.returncode == 0, r.stdout[-2000:]
    report, _ = evaluate(SPECS_STEP5["checkout_abandonment"], str(exp), json.load(open(exp / "manifest.json")))
    assert report["status"] in ("PASSED", "REJECTED"), report.get("reasons")
    assert report["split"]["test_rows"] > 0 and report["leakage_checks"] == "passed"
    seg = report["segments"]
    assert seg["first_time_customers"]["rows"] > 0 and seg["returning_customers"]["rows"] > 0
    d = report["details"]
    assert "model_top10_false_predictions" in d and "rule_top10_false_predictions" in d and "calibration_error_ece" in d
    assert any(g["name"].startswith("first-time") for g in report["guards"])


