def _vd():
    spec = importlib.util.spec_from_file_location("vd", os.path.join(BASE, "scripts", "validate_datasets.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _h(kind, i):
    return kind + hashlib.sha256(f"fx:{kind}:{i}".encode()).hexdigest()[:16]


def checkout_fixture(n=3000, seed=0):
    rng = np.random.default_rng(seed)
    ts = pd.Timestamp("2026-01-01", tz="UTC") + pd.to_timedelta(np.sort(rng.uniform(0, 180, n)), unit="D")
    first = rng.random(n) < 0.4
    views, sel = rng.poisson(2, n), rng.poisson(1, n)
    prior_exp = np.where(first, 0, rng.poisson(0.5, n))
    logit = -0.8 + 0.9 * prior_exp - 0.4 * sel + 0.3 * first + rng.normal(0, 1, n)
    y = (rng.random(n) < 1 / (1 + np.exp(-logit))).astype(int)
    prior_p = np.where(first, 0, rng.integers(1, 5, n))
    return pd.DataFrame({
        "order_id": [_h("O", i) for i in range(n)], "customer_id": [_h("C", i % 900) for i in range(n)], "event_id": [_h("E", i % 120) for i in range(n)],
        "ts": ts.strftime("%Y-%m-%dT%H:%M:%S.000Z"), "event_type": rng.choice(["MUSIC_CONCERT", "CRICKET_MATCH"], n), "city": rng.choice(["Lahore", "Karachi"], n),
        "country": "PK", "payment_method": "STRIPE", "tickets_requested": rng.integers(1, 5, n), "unit_price_rel": rng.uniform(0.5, 2, n).round(3),
        "hours_since_sales_open": rng.uniform(0, 500, n).round(2), "days_until_event": rng.uniform(1, 60, n).round(2), "account_age_days": rng.uniform(0, 400, n).round(2),
        "customer_prior_orders": prior_p + rng.integers(0, 2, n), "customer_prior_purchases": prior_p, "customer_prior_expired_checkouts": prior_exp,
        "first_time": first.astype(int), "visit_event_views": views, "visit_seat_selections": sel, "abandoned": y, "feature_source": "snapshot",
    })


def hourly_fixture(events=300, hours=8, seed=1):
    rng = np.random.default_rng(seed)
    rows = []
    for e in range(events):
        t0 = pd.Timestamp("2026-01-01", tz="UTC") + pd.Timedelta(days=float(e) * 0.6)
        pace = rng.choice([0, 0, 2, 6, 15])
        sold = 0
        for h in range(hours):
            last = rng.poisson(pace)
            sold += last
            rows.append({"event_id": _h("E", e), "organizer_id": _h("G", e % 40), "ts": (t0 + pd.Timedelta(hours=6 * h)).strftime("%Y-%m-%dT%H:%M:%S.000Z"),
                         "event_type": "MUSIC_CONCERT", "city": "Lahore", "country": "PK", "day_of_week": "Friday", "venue_capacity": 500, "tier_count": 2,
                         "min_price_rel": 0.8, "avg_price_rel": 1.0, "max_price_rel": 1.5, "start_hour": 20, "start_month": 3, "organizer_past_events": int(e % 5),
                         "organizer_past_sell_through_48h": None if e % 5 == 0 else 0.1, "hours_since_sales_open": 6.0 * h, "days_until_event": 30 - h,
                         "sold_so_far": sold, "sold_last_24h": last, "sell_through_so_far": round(sold / 500, 4), "rule_next_24h": last,
                         "sales_next_24h": int(rng.poisson(pace * 1.1)), "feature_source": "snapshot"})
    return pd.DataFrame(rows)


def write_export(tmp, step5):
    """A db-export-shaped DEVELOPMENT FIXTURE: empty base files + the given Step 5 files."""
    vd = _vd()
    out = tmp / "export"
    out.mkdir()
    files = {}
    for name, cols in vd.SCHEMA.items():
        pd.DataFrame(columns=cols).to_csv(out / f"{name}.csv", index=False)
        files[name] = {"rows": 0, "sha256": hashlib.sha256((out / f"{name}.csv").read_bytes()).hexdigest()}
    for name, df in step5.items():
        df.to_csv(out / f"{name}.csv", index=False)
        files[name] = {"rows": int(len(df)), "sha256": hashlib.sha256((out / f"{name}.csv").read_bytes()).hexdigest()}
    pd.DataFrame(columns=["event_id", "sales_open", "event_start"]).to_csv(out / "events.csv", index=False)
    man = {"source": "db-export", "test_fixture": True, "contains_test_data": True, "feature_sources": ["snapshot"], "source_class": "GENUINE_CUSTOMER",
           "history": {"from": "2025-12-01T00:00:00Z", "to": "2026-07-01T00:00:00Z"}, "files": files, "deployed_models": {}}
    json.dump(man, open(out / "manifest.json", "w"))
    return out


