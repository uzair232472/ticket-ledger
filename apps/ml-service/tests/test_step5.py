@pytest.mark.slow
def test_threshold_retraining_and_failure_recovery(tmp_path):
    exp = write_export(tmp_path, {"checkout_abandonment": checkout_fixture()})
    rep, out = tmp_path / "rep", tmp_path / "models"
    run = lambda extra=(), env=None: subprocess.run([PY, "scripts/auto_retrain.py", "--data", str(exp), "--reports", str(rep), "--out", str(out), "--allow-test-fixture", *extra],
                                                    cwd=BASE, capture_output=True, text=True, env={**os.environ, **(env or {})}, timeout=900)
    # A failed training run leaves no partial candidate and does not advance the threshold state
    r = run(env={"ML_RETRAIN_FAULT": "train"})
    assert r.returncode == 1 and "TRAINING_FAILED" in r.stdout, r.stdout
    assert not out.exists() or not any(out.iterdir())
    assert not (rep / "last_run.json").exists()
    # Recovery: the next run trains
    r = run()
    assert r.returncode == 0 and "RAN" in r.stdout, r.stdout + r.stderr
    s = json.load(open(next(p for p in sorted(rep.glob("*/retrain_summary.json")) if json.load(open(p))["status"] == "RAN")))
    assert s["models"]["checkout_abandonment"]["trained"] and s["promoted"] is False
    assert (rep / "last_run.json").exists()
    # Threshold: no new verified rows -> not retrained
    r = run(["--min-new-rows", "100"])
    assert "NOTHING_TO_TRAIN" in r.stdout
