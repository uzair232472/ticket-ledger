def test_drift_detects_a_shift_and_ignores_none():
    rng = np.random.default_rng(3)
    a = pd.DataFrame({"x": rng.normal(0, 1, 2000), "c": rng.choice(["a", "b"], 2000)})
    b = pd.DataFrame({"x": rng.normal(1.5, 1, 2000), "c": rng.choice(["a", "b"], 2000)})
    r = drift_report(a, b, ["x", "c"])
    assert "x" in r["drifted"] and "c" not in r["drifted"]
    assert time_drift(a.assign(ts=range(2000)), ["x"])["status"] == "MEASURED"


def test_validator_rejects_a_personalised_control_and_unlabelled_source(tmp_path):
    bad = rec_fixture(n_cust=20)
    bad.loc[bad["variant"] == "CONTROL", "basis"] = "personal"
    exp = write_export(tmp_path, {"recommendation_impressions": bad})
    r = subprocess.run([PY, "scripts/validate_datasets.py", "--data", str(exp), "--allow-test-fixture"], cwd=BASE, capture_output=True, text=True)
    assert r.returncode == 1 and "control group is never personalised" in r.stdout
    man = json.load(open(exp / "manifest.json"))
    man.pop("test_fixture")
    man.pop("source_class")
    man["contains_test_data"] = False
    json.dump(man, open(exp / "manifest.json", "w"))
    r = subprocess.run([PY, "scripts/validate_datasets.py", "--data", str(exp)], cwd=BASE, capture_output=True, text=True)
    assert r.returncode == 1 and "data-source class GENUINE_CUSTOMER" in r.stdout


