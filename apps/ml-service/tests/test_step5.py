def rec_fixture(n_cust=1500, effect=0.04, seed=2):
    rng = np.random.default_rng(seed)
    rows = []
    for c in range(n_cust):
        v = "CONTROL" if c % 2 else "PERSONALISED"
        first = int(rng.random() < 0.3)
        for k in range(2):
            for pos in range(1, 4):
                p_click = 0.05 + (0.03 if v == "PERSONALISED" else 0)
                p_buy = 0.03 + (effect if v == "PERSONALISED" else 0)
                rows.append({"list_id": _h("L", f"{c}-{k}"), "customer_id": _h("C", c), "event_id": _h("E", (c + pos) % 60), "ts": "2026-03-01T00:00:00.000Z",
                             "variant": v, "basis": "personal" if v == "PERSONALISED" and not first else "population", "surface": "home", "position": pos,
                             "popularity_rank": int(rng.integers(1, 60)), "exploration": int(pos == 3), "is_new_event": int(rng.random() < 0.2), "first_time": first,
                             "clicked": int(rng.random() < p_click), "purchased_7d": int(rng.random() < p_buy), "feature_source": "impression-log"})
    return pd.DataFrame(rows)


def test_recommendation_report_measures_uplift_against_control_and_exposure():
    rep = recommendation_report(rec_fixture())
    assert rep["status"] == "MEASURED"
    assert rep["purchase_uplift"] > 0 and rep["purchase_uplift_95ci"][0] > 0
    assert set(rep["first_time_vs_returning"]) == {"first_time", "returning"}
    assert rep["exposure"]["distinct_events"] > 0 and 0 <= rep["exposure"]["exposure_gini"] <= 1
    small = recommendation_report(rec_fixture(n_cust=50))
    assert small["status"] == "NOT_ENOUGH_DATA" and small["short"]
    assert recommendation_report(rec_fixture().iloc[:0])["status"] == "NO_DATA"


